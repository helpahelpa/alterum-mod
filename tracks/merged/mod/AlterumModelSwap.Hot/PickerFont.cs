    private static int Index(char c)
    {
        c = char.ToUpperInvariant(c);
        for (int i = 0; i < Chars.Length; i++) if (Chars[i] == c) return i;
        return Chars.IndexOf('?');
    }

    // True when the glyph pixel at (col,row) is set, for a char that Index() resolved.
    internal static bool Pixel(char c, int col, int row)
    {
        int g = Index(c);
        if (g < 0 || col < 0 || col >= GlyphWidth || row < 0 || row >= GlyphHeight) return false;
        return (Bits[g * GlyphHeight + row] & (1 << (GlyphWidth - 1 - col))) != 0;
    }
