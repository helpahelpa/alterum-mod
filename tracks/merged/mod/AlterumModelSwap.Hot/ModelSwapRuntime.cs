    // Placement is deliberately request-file only now: `reel.request place=here` lands here (see
    // TryConsumePlaceRequest above), and every saved anchor is loaded by ReelPlacements. There is
    // no shortcut key and no key handler any more - F4/`mod.reel.place` was deleted outright, not
    // defaulted off, so a stale override for it is dropped as an unknown id on the next load.
    // An existing manual booth is re-anchored by LobbyPropRuntime.PlaceHere and a map run with no
    // manual booth creates one at the pose LobbyPropRuntime resolves for PlaceHere. The reel is
    // map-only: the lobby has no booth, so a placement request there is logged and ignored.

    // The booth request handling and the manual placement act on: the manual booth when one exists,
    // otherwise the first live map booth. Derived every frame so a dead reference never survives a
    // scene change.
    private LobbyPropRuntime PrimaryReel()
    {
        if (_manual != null && _manual.Root != null) return _manual;
        for (int i = 0; i < _reels.Count; i++)
            if (_reels[i] != null && _reels[i].Root != null) return _reels[i];
        return null;
    }

    // Site the prop where the player is standing, in front of them and floor-snapped. Floor probe
    // starts above their head and falls back to their feet, so a map without a collider under the
    // cell still puts the base on the ground plane they stand on. Map-only: the lobby has no reel.
    private bool PlacePropAtPlayer(IHostContext log, string why, out string path)
    {
        if (!ReelLogic.IsMapRun(out string scene))
        {
            path = "skipped";
            log.LogInfo($"[reel] place skipped ({why}): the reel is map-only; scene='{scene}'");
            return false;
        }
        // A manual booth whose GameObject died with its scene is not a booth: replace it.
        if (_manual != null && _manual.Root == null)
        {
            try { _manual.Dispose(); } catch (Exception e) { log.LogWarning($"[prop] old prop dispose failed: {e.Message}"); }
            _manual = null;
        }
        if (_manual != null)
        {
            path = "PlaceHere";
            return _manual.PlaceHere(log, why);
        }
        path = "create";
        _manual = LobbyPropRuntime.CreateAtPlayer(log, why);
        if (_manual == null) return false;
        _manual.IsManual = true;
        _reels.Add(_manual);
        log.LogInfo($"[reel:spawn] manual booth created why={why} pos=({_manual.Anchor.x:F2},{_manual.Anchor.y:F3},{_manual.Anchor.z:F2}) " +
                    $"yaw={_manual.Yaw:F1} live={_reels.Count}");
        return true;
    }

