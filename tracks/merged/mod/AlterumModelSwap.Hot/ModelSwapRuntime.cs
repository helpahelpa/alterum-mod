// Reloadable half of the mod. Nothing here may call ClassInjector: injected types live in
// the host assembly and cannot be re-registered after a reload.
public class ModelSwapRuntime
{
    // Placement chosen in game and baked in. World space, Lobby scene.
    private const bool UseFixedLobbyPose = true;
    private const int FrameCap = 15;
    // Explicit opt-in for local development display restrictions; normal players retain game settings.
    // A live test session can opt in without restarting an existing game process.
    private bool DevDisplayMode => DevDisplayPolicy.Enabled(Environment.GetCommandLineArgs()) ||
        (!string.IsNullOrEmpty(_h.ScreensDir) && System.IO.File.Exists(System.IO.Path.Combine(_h.ScreensDir, "dev-display.enabled")));
    private float _nextFpsCheck;
    private static readonly Vector3 FixedLobbyPos = new Vector3(-0.328f, 1.153f, -12.273f);
    private static readonly Vector3 FixedLobbyEuler = new Vector3(0f, 41.06f, 0f);

    private readonly IHostContext _h;

    // The overlay legend and the startup [keys] line are both generated by ModBindings.Legend(),
    // i.e. from the one shortcut table that also dispatches. A legend entry and the handler that
    // polls that key therefore cannot disagree, and a rebind moves both at once. This file keeps
    // no second copy of the map (the old KeyLegend constant here was that second copy).
    private ConfigSnapshot _cfg;

    private readonly bool _firstActivation;

    public ModelSwapRuntime(IHostContext host, bool firstActivation)
    {
        _h = host;
        _firstActivation = firstActivation;
        _cfg = host.Config;
        // No Unity calls in the constructor: the cosmetics module only reads its state file here
        // and loads the embedded asset pack on the first Update (main thread).
        if (!AlterumModelSwap.DiagnosticsMode.Enabled)
            _cosmetics = new CosmeticsRuntime(host);
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct RECT { public int Left, Top, Right, Bottom; }

    [DllImport("user32.dll")] private static extern bool GetWindowRect(IntPtr hWnd, out RECT rect);
    [DllImport("user32.dll")] private static extern bool SetWindowPos(IntPtr h, IntPtr after, int x, int y, int cx, int cy, uint flags);
    [DllImport("user32.dll")] private static extern IntPtr GetForegroundWindow();
    [DllImport("user32.dll")] private static extern bool SetForegroundWindow(IntPtr h);
    [DllImport("user32.dll")] private static extern bool ShowWindow(IntPtr h, int cmd);
    [DllImport("user32.dll")] private static extern void keybd_event(byte vk, byte scan, uint flags, UIntPtr extra);

    private float _t;
    private bool _inited;
    private IntPtr _myHwnd = IntPtr.Zero;
    private IntPtr _prevFg = IntPtr.Zero;
    private float _nextAssert;
    private float _nextSizeTry;
    private bool _wasFullscreenLogged;
    private bool _wasSizeLogged;
    private bool _windowLogged;
    private int _lastLeft = int.MinValue, _lastTop = int.MinValue;

    private bool _dumpedModels;
    private int _shots;
    private string _lastScene = "";
    private readonly HashSet<string> _seenInstances = new();

    private GameObject _mirror;
    private MirrorRuntime _mirrorRt;
    // Reel of Fortune booths. Map entry spawns one per saved anchor (Lair/Necropolis have two);
    // `reel.request place=here` adds or repositions a separate manual booth so it never moves an
    // anchor (the F4 shortcut that used to do this was removed). Both lists are owned and
    // destroyed by this generation, never by a scene reload.
    private readonly List<LobbyPropRuntime> _reels = new List<LobbyPropRuntime>();
    private LobbyPropRuntime _manual;
    private Proportions _proportions;
    private EmoteRuntime _emote;
    private float _emoteDt;
    private CosmeticsRuntime _cosmetics;
    private PickerUI _pickers;
    // The emote runtime's verify camera can render the mirror's own RenderTexture; nothing else
    // outside this class reads it.
    internal RenderTexture MirrorTexture => _mirrorRt != null ? _mirrorRt.rt : null;
    private RenderTexture GetMirrorTexture() => MirrorTexture;
    private float _nextMirrorValidation;
    // Delegate for the mirror-RT evidence path in ClothesToggle; a method group, so no per-frame
    // closure allocation and it always resolves the mirror that exists now.
    private Func<RenderTexture> _mirrorTextureFn;
    private bool _suppressAuto;
    private DateTime _cfgMtime = DateTime.MinValue;
    private float _nextCfgCheck;
    private string _overlayInfo = "";
    private Vector3 _camAnchor;
    private float _camStill;
    private Camera _gameCam;
    private float _nextAutoMirror;
    private bool _rendered;
    private bool _abortSequence;
    private string[] _clicks;
    private int _clickIndex;
    private float _nextClickAt = -1f;

    internal void DiagnosticsTick(float dt)
    {
        _t += dt;
        _cfg = _h.Config;
        EnforceFrameCap();
        // Display controls are explicitly gated by dev mode and the instance config;
        // they do not alter gameplay and are needed when the game restores fullscreen.
        KeepQuiet();
        string scene = SceneManager.GetActiveScene().name;
        if (scene != _lastScene)
        {
            _lastScene = scene;
            _h.LogInfo($"[scene] -> '{scene}' at t={_t:F1}");
        }
    }

    public void Update(float dt)
    {
        try
        {
            _t += dt;
            var previousConfig = _cfg;
            _cfg = _h.Config;
            if (previousConfig.MirrorShowPlayer != _cfg.MirrorShowPlayer ||
                previousConfig.MirrorWidth != _cfg.MirrorWidth || previousConfig.MirrorHeight != _cfg.MirrorHeight ||
                previousConfig.MirrorFrame != _cfg.MirrorFrame || previousConfig.MirrorLobbyOnly != _cfg.MirrorLobbyOnly)
            {
                DestroyMirror();
                _h.LogInfo("[mirror] configuration changed; restoring body and recreating fixed viewpoint");
            }
            var log = _h;

            if (!_inited) { _inited = true; Init(); }

            // Emote runtime (track `emotes`): attached once the scene is up. It owns the local
            // skeleton only while a clip is active, through the game's own disable lease.
            if (_emote == null && _t > 2f)
            {
                _emote = new EmoteRuntime(_h, () => MirrorTexture);
                _h.LogInfo("[emote] runtime attached (U opens the emote picker; a click plays, no emote key)");
            }
            // Emote runtime first, then the pickers. Nothing polls an emote key any more (the
            // pickers' open keys are the only World rows besides POV/console), so the ordering is
            // kept for the tick itself: a pick starts after the emote update and a cosmetic toggle
            // still lands before _cosmetics.Update() below, so Reconcile runs in the same frame.
            _emoteDt = dt;
            Perf.W("emote", () => _emote?.Update(dt));
            // Stage 3A: a local emote start/stop is one event to the mod-confirmed peers. The id is
            // the catalogue id the observer resolves from its own pack/graph; nothing else travels.
            try { RemoteModels.PublishLocalEmote(log, _emote == null ? "" : _emote.PlayingId); }
            catch (Exception e) { log.LogWarning($"[swap:emote] publish failed: {e.Message}"); }
            if (_emote != null && _pickers == null) _pickers = new PickerUI(_h, _emote, _cosmetics);
            Perf.W("pickers", () => _pickers?.Tick(dt));
            // The game's own console is on Tilde; GameConsole ticks it at the end of
            // HotModule.Update (scene-ready enable + the qc.request verbs).
            Perf.W("quiet", KeepQuiet);
            Perf.W("framecap", EnforceFrameCap);

            string scene = SceneManager.GetActiveScene().name;
            if (scene != _lastScene)
            {
                _lastScene = scene;
                _camStill = 0f; _camAnchor = Vector3.zero;
                _suppressAuto = false;
                DestroyMirror();                      // scene unload destroys the GameObject, not the assets
                log.LogInfo($"[scene] -> '{scene}' at t={_t:F1}");
                // Pay the first object-table scans in the transition, not on the first gameplay
                // frame that happens to need a camera or the map identity. The player types are
                // already warmed by MapBody.OnScene's first census.
                try { SceneCache.Prewarm(Il2CppType.Of<Camera>()); } catch { }
                try { ReelPlacements.Prewarm(log); } catch (Exception e) { log.LogWarning($"[reel:place] prewarm failed: {e.Message}"); }
                try { MapBody.OnScene(log, scene); } catch (Exception e) { log.LogWarning($"[mapbody] scene probe failed: {e.Message}"); }
                LogLiveInstances();
            }

            if (!_dumpedModels && _t > 3f) _dumpedModels = DumpModelTable();

            // Global MagicaCloth loop recovery. Per frame, not per sweep: it is readiness-gated
            // and manager-scoped, and a re-created manager (scene change) must get a fresh
            // attempt without waiting for the next 1 Hz sweep.
            Perf.W("clothsim", () => ClothSim.Tick(_h));
            // Diagnostics for that intervention: step-callback counters and the cost window.
            Perf.W("clothmetrics", () => ClothMetrics.Tick(_h, dt));

            // Bone pass: enlarge breasts (female rigs) / hips (all rigs) and keep the shipped
            // breast cloth reported. Its own SetupModel postfix pulls the sweep forward.
            if (_proportions == null)
            {
                _proportions = new Proportions(_h);
                // The enhancement state (chest on / hips off on a fresh config) has to be applied
                // before the first SetupModel, not on the first frame that happens to tick the
                // pass: the bone pass is what reads it. EnsureLoaded is idempotent and also drives
                // Apply(), which is what hands the values to Proportions/JiggleSolver/CustomEnh.
                try { EnhancementSettings.EnsureLoaded(_h); }
                catch (Exception e) { _h.LogWarning($"[enh] load failed: {e.Message}"); }
            }
            Perf.W("proportions", () => _proportions.Tick(_t));
            // Proportion capture rig (fixed ortho camera, frozen pose, chestdump/measure probes).
            // Inert unless BepInEx/screens/propcap.request exists: it polls at 2 Hz and returns.
            Perf.W("propshots", () => ProportionShots.Tick(_h, _proportions));
            // Our own Verlet jiggle for the two chest leaves. Request/rescan only; the write phase
            // runs in LateUpdate, after the game's animation has written the skeleton.
            Perf.W("jigsolve", () => JiggleSolver.Tick(_h));
            Perf.W("bonesprobe", () => BonesProbe.Tick(_h, MirrorCamera, dt));
            Perf.W("jigprobe", () => JiggleProbe.Tick(_h, dt));

            // Unattended spawn-source probe (spawn.request) + the reel's per-map item eligibility.
            // Both are no-ops in the lobby/without a request; the eligibility refresh only runs on
            // a scene change, so a spin never rescans the scene (see ReelEligible).
            try { Perf.W("spawnprobe", () => SpawnProbe.Tick(_h)); }
            catch (Exception e) { log.LogWarning($"[spawn] tick threw: {e.Message}"); }
            // Free-camera proof frame (proofcam.request): one render from a requested eye/lookat,
            // in any scene. Inert unless the request file exists (2 Hz poll).
            try { Perf.W("proofcam", () => ProofCam.Tick(_h)); }
            catch (Exception e) { log.LogWarning($"[proofcam] tick threw: {e.Message}"); }
            try { Perf.W("reeleligible", () => ReelEligible.Tick(_h)); }
            catch (Exception e) { log.LogWarning($"[reel:pool] tick threw: {e.Message}"); }

            // Third-person toggle (track `cosmetics`, F7 / pov.request). Refresh the cosmetic
            // screen policy in the same frame, so a mode change and its [cosmetic:view] line are
            // always adjacent. It must run before the cosmetics update below.
            if (PovToggle.Tick(log, _t)) _cosmetics.ForcePovRefresh();
            Perf.Phase("update");

            // The mirror is part of the lobby: place it (or re-place it after a scene reload)
            // as soon as a local player exists in the Lobby scene.
            bool lobbyScene = !_cfg.MirrorLobbyOnly ||
                              (scene != null && scene.IndexOf("Lobby", StringComparison.OrdinalIgnoreCase) >= 0);
            // Only place once the view has stopped moving: the lobby camera starts somewhere else
            // and flies to the player, and Camera.main can briefly resolve to another camera.
            Camera cam = null;
            if (_cfg.AutoMirror && !_suppressAuto && lobbyScene && _mirror == null)
            {
                cam = FindGameCamera();
                if (cam != null)
                {
                    // settle on total displacement from a fixed anchor, not per-frame delta
                    Vector3 p0 = cam.transform.position;
                    if ((p0 - _camAnchor).sqrMagnitude > 0.0025f) { _camAnchor = p0; _camStill = 0f; }
                    else _camStill += Time.unscaledDeltaTime;
                }

                if (cam != null && _camStill > 1.0f &&
                    _t > _cfg.AutoMirrorDelay && _t > _nextAutoMirror)
                {
                    _nextAutoMirror = _t + 1.5f;
                    _gameCam = cam;
                    PlaceMirror();
                }
            }

            // Named placements: spawn every saved anchor for this map (two on Lair and Necropolis)
            // once per map generation. No-op outside a map run - the lobby has no booth - and the
            // spawner refuses to add a second set after a hot reload until the retiring generation
            // has removed its own.
            if (_t > 2.5f)
            {
                try { Perf.W("reelplace", () => ReelPlacements.Tick(log, _reels)); }
                catch (Exception e) { log.LogWarning($"[reel:spawn] tick threw: {e.Message}"); }
            }
            if (_manual != null && _manual.Root == null)
            {
                try { _manual.Dispose(); } catch (Exception e) { log.LogWarning($"[prop] old prop dispose failed: {e.Message}"); }
                _manual = null;
            }
            // One booth owns <ScreensDir>/reel.request; the others still answer E when looked at.
            var primary = PrimaryReel();
            for (int i = 0; i < _reels.Count; i++) _reels[i].RequestOwner = ReferenceEquals(_reels[i], primary);

            // `reel.request place=here` is the only way to add or reposition the manual booth; the
            // F4 key that used to do the same was removed.
            if (_t > 2.5f && LobbyPropFactory.TryConsumePlaceRequest(log))
            {
                PlacePropAtPlayer(log, "reel.request", out _);
            }
            // Every booth ticks its own look test, E handling and spin state. Only the request owner
            // reads reel.request (and advances the shared HUD clock), so the file is consumed once.
            for (int i = 0; i < _reels.Count; i++)
            {
                var rt = _reels[i];
                if (rt == null) continue;
                try { Perf.W("prop", () => rt.Tick(dt)); }
                catch (Exception e) { log.LogWarning($"[reel] prop tick threw: {e.Message}"); }
            }
            // A map with no saved anchor (or a scene that never had a booth) still answers the
            // placement lines of reel.request through the store, not through a booth.
            if (primary == null && _t > 2.5f) ReelPlacements.PollRequest(log, null);

            Perf.W("mirrorvis", () => _mirrorRt?.Visibility?.Update());
            // Garment hide (clothes.request only; the F5 row was pruned). It runs AFTER the mirror's own visibility sweep:
            // a wardrobe switch makes that sweep Rebind the local body and write
            // forceRenderingOff=false on every renderer it drives, so the re-assert has to follow it
            // in the same frame. Nothing here writes Renderer.enabled, layers or the body binding.
            Perf.W("clothes", () => ClothesToggle.Tick(log, _mirrorTextureFn));
            // Sahur body (sahur.request; the F2/F3 rows were pruned): a rigid-bind model on the game's own bones. It
            // hides the body renderers while active, so it runs after the mirror's visibility sweep
            // and the garment pass, whose own writes are re-asserted against this one.
            try { Perf.W("sahur", () => SahurModel.Tick(log, dt)); }
            catch (Exception e) { log.LogError($"[sahur] tick threw: {e}"); }
            // Rigged Sahur variant (sahurrig.request; the F1 row was pruned): its own 71-bone Mixamo skeleton retargeted
            // from this rig. Only resolves/builds here; the pose is written in LateUpdate.
            try { Perf.W("sahurrig", () => SahurRig.Tick(log, dt)); }
            catch (Exception e) { log.LogError($"[sahurrig] tick threw: {e}"); }
            // Sahur wardrobe entry: a real PlayerModelData appended to PlayerModelDatabase.Models,
            // its portrait, and the lobby tabs that select it. No-op until a local player exists;
            // the lobby-only UI part no-ops outside the lobby.
            try { Perf.W("wardrobe", () => SahurWardrobe.Tick(log, dt)); }
            catch (Exception e) { log.LogError($"[sahur:wardrobe] tick threw: {e}"); }
            // `[mapbody]`: why the local custom body is or is not on screen in a map (read-only).
            try { Perf.W("mapbody", () => MapBody.Tick(log, dt)); }
            catch (Exception e) { log.LogWarning($"[mapbody] tick threw: {e.Message}"); }
            // Wardrobe PREVIEW body: the wardrobe instantiates its own ThirdViewPlayerModel per
            // model data, separate from the player's. While one of our entries is applied, this
            // hides that instance's body and attaches the matching Sahur model to its skeleton.
            try { Perf.W("preview", () => SahurPreview.Tick(log, dt)); }
            catch (Exception e) { log.LogError($"[sahur:preview] tick threw: {e}"); }
            // Stage-2 sync: peers' chosen slugs in, our own out (through the same bridge), and the
            // presentation built on each remote player's skeleton. Drains the bridge ring here, so
            // it must run before anything else that consumes inbound frames.
            try { Perf.W("remote", () => RemoteModels.Tick(log, dt)); }
            catch (Exception e) { log.LogError($"[swap:remote] tick threw: {e}"); }
            // Results screen bodies: re-apply published/peer slugs to the models the game builds
            // per ResultPlayer in the Results scene. Runs after the remote tick so peer states
            // this frame are already resolved.
            try { Perf.W("resultsbody", () => ResultsBodies.Tick(log, dt)); }
            catch (Exception e) { log.LogWarning($"[results:body] tick threw: {e.Message}"); }
            // Identity/presentation resolver: the ONE canonical answer to "which row is this actor
            // wearing", used by the body decision, the bottom-right HUD portrait and the wardrobe's
            // remote occupancy. Edge-driven (selection/database/peer-state/UI attach); the display
            // corrections it makes are display-only (no PlayerModelData write, no SetupModel, no
            // selection RPC) and indices stay local - only slugs travel. Runs after the wardrobe and
            // remote ticks so a change made this frame is already visible to it.
            try { Perf.W("modelpres", () => ModelPresentation.Tick(log, _t)); }
            catch (Exception e) { log.LogWarning($"[model:identity] tick threw: {e.Message}"); }

            // Cosmetic attach/screen policy (track `cosmetics`), after the mirror's own visibility
            // sweep so a fresh body binding is already known, and before LateUpdate renders.
            Perf.W("cosmetics", () => _cosmetics?.Update());
            if (_mirrorRt != null && _t >= _nextMirrorValidation)
            {
                _nextMirrorValidation = _t + 1f;
                if (MirrorFactory.BodyLayerConflicts(_mirrorRt.BodyLayer, _mirrorRt.Visibility))
                {
                    log.LogWarning("[mirror:body-layer-conflict] screen camera now includes isolated body bit; restoring and recreating");
                    DestroyMirror();
                }
            }

            RunClicks();

            if (!_rendered && _t > _cfg.RenderDelay) { _rendered = true; RenderWardrobeSlots(); }

            if (_cfg.TakeScreenshots &&
                _t > _cfg.ScreenshotInterval * (_shots + 1) && _shots < 40)
            {
                _shots++;
                Shot($"shot{_shots:00}");
            }
        }
        catch (Exception e) { _h.LogError($"Update threw: {e}"); }
    }

    private void Init()
    {
        var log = _h;
        _mirrorTextureFn = GetMirrorTexture;
        Application.runInBackground = true;
        EnforceFrameCap();
        try
        {
            log.LogInfo($"[build] game '{Application.version}' on Unity {Application.unityVersion} " +
                        $"(plugin built against this game's interop)");
        }
        catch { }
        try
        {
            _myHwnd = System.Diagnostics.Process.GetCurrentProcess().MainWindowHandle;
            var fg = @"C:\Windows\Temp\alterum\fg.json";
            if (System.IO.File.Exists(fg))
            {
                var m = System.Text.RegularExpressions.Regex.Match(System.IO.File.ReadAllText(fg), "\"hwnd\"\\s*:\\s*(\\d+)");
                if (m.Success) _prevFg = new IntPtr(long.Parse(m.Groups[1].Value));
            }
            log.LogInfo($"[quiet] init hwnd={_myHwnd} previousForeground={_prevFg}");
        }
        catch (Exception e) { log.LogWarning($"[quiet] init failed: {e.Message}"); }

        string seq = _firstActivation ? _cfg.ClickSequence : null;
        if (!string.IsNullOrEmpty(seq))
        {
            _clicks = seq.Split('|');
            _nextClickAt = _cfg.ClickFirstDelay;
            log.LogInfo($"[auto] click sequence: {seq}");
        }

        // The three tracks were developed with overlapping function keys. The merged map gives every
        // action its own key and lives in ModBindings (stream C's registry); this line and the
        // overlay legend are generated from it, so nothing here is the automation path either
        // (request files are). Every entry is rebindable from Settings > Controls and the ESC menu.
        try { log.LogInfo($"[keys] {ModBindings.Legend()}"); }
        catch (Exception e) { log.LogWarning($"[keys] legend failed: {e.Message}"); }
    }

    // Cap the frame rate so two simultaneous instances do not fight over the machine.
    // The game re-applies its own display settings a few seconds into startup, which resets
    // vSync/targetFrameRate too, so re-assert periodically. vSync must stay 0 or Unity
    // ignores targetFrameRate entirely.
    private void EnforceFrameCap()
    {
        if (!DevDisplayMode) return;
        try
        {
            if (_t < _nextFpsCheck) return;
            _nextFpsCheck = _t + 2f;
            if (QualitySettings.vSyncCount == 0 && Application.targetFrameRate == FrameCap) return;
            QualitySettings.vSyncCount = 0;
            Application.targetFrameRate = FrameCap;
            _h.LogInfo($"[fps] cap applied {FrameCap} (vSync off)");
        }
        catch (Exception e) { _h.LogWarning($"[fps] enforce failed: {e.Message}"); }
    }

    // Enforce windowed + off-screen every frame; the game re-applies its own saved
    // display settings a few seconds into startup, which would otherwise go fullscreen.
    private void KeepQuiet()
    {
        if (!DevDisplayMode || (!_cfg.ForceWindowed && !_cfg.Quiet)) return;
        var log = _h;

        if (_myHwnd == IntPtr.Zero) _myHwnd = System.Diagnostics.Process.GetCurrentProcess().MainWindowHandle;

        // Enforce the configured size, not only leaving fullscreen: a client launched
        // borderless at a larger resolution stays there otherwise, because Unity only
        // re-applies the launch args on startup. Retried on a cooldown so a refused or
        // asynchronous SetResolution cannot thrash the swap chain every frame.
        bool sizeWrong = !_cfg.Quiet && (Screen.width != _cfg.QuietWidth || Screen.height != _cfg.QuietHeight);
        if (Screen.fullScreen || (sizeWrong && _t >= _nextSizeTry))
        {
            Screen.fullScreen = false;
            Screen.SetResolution(_cfg.QuietWidth, _cfg.QuietHeight, false);
            _nextSizeTry = _t + 1f;
            if (!_wasFullscreenLogged) { _wasFullscreenLogged = true; log.LogInfo($"[window] enforcing windowed {_cfg.QuietWidth}x{_cfg.QuietHeight} at t={_t:F2}"); }
            if (!_wasSizeLogged && sizeWrong) { _wasSizeLogged = true; log.LogInfo($"[window] resizing {Screen.width}x{Screen.height} -> {_cfg.QuietWidth}x{_cfg.QuietHeight} at t={_t:F2}"); }
            _nextAssert = 0f;
        }

        if (_t >= _nextAssert)
        {
            _nextAssert = _t + 0.5f;
            const uint SWP_NOSIZE = 0x0001, SWP_NOZORDER = 0x0004, SWP_NOACTIVATE = 0x0010;
            if (_myHwnd != IntPtr.Zero)
            {
                // Quiet parks it off-screen; otherwise place it at the configured spot.
                // Size comes from the -screen-width/-screen-height launch args; moving the
                // window only, and only when it is in the wrong place, avoids fighting Unity
                // (which recentres the window whenever the resolution changes).
                int x = _cfg.Quiet ? -6000 : _cfg.WindowX;
                int y = _cfg.Quiet ? 0 : _cfg.WindowY;
                RECT r;
                bool moved = false;
                if (GetWindowRect(_myHwnd, out r))
                {
                    if (r.Left != _lastLeft || r.Top != _lastTop)
                    {
                        // Log only when the window actually changed position, so an unstable
                        // window is obvious in the log instead of a one-off line.
                        if (_lastLeft != int.MinValue)
                            log.LogInfo($"[window] moved ({_lastLeft},{_lastTop}) -> ({r.Left},{r.Top})");
                        _lastLeft = r.Left; _lastTop = r.Top;
                    }
                    if (Math.Abs(r.Left - x) > 2 || Math.Abs(r.Top - y) > 2)
                        moved = SetWindowPos(_myHwnd, IntPtr.Zero, x, y, 0, 0, SWP_NOSIZE | SWP_NOZORDER | SWP_NOACTIVATE);
                }
                if (!_windowLogged)
                {
                    _windowLogged = true;
                    log.LogInfo($"[window] {Screen.width}x{Screen.height} windowed at ({x},{y}) quiet={_cfg.Quiet} moved={moved}");
                }
            }
        }

        // If the game grabbed focus, hand it back to whatever the user was using.
        if (_cfg.Quiet && _prevFg != IntPtr.Zero && GetForegroundWindow() == _myHwnd)
        {
            keybd_event(0x12, 0, 0, UIntPtr.Zero);
            ShowWindow(_prevFg, 9);
            SetForegroundWindow(_prevFg);
            keybd_event(0x12, 0, 2, UIntPtr.Zero);
        }
    }

    private void RunClicks()
    {
        if (_clicks == null || _clickIndex >= _clicks.Length) return;
        if (_abortSequence) return;
        if (_t < _nextClickAt) return;

        string name = _clicks[_clickIndex].Trim();

        if (name.StartsWith("@"))
        {
            _clickIndex++;
            _nextClickAt = _t + _cfg.ClickStepDelay;
            if (name.Equals("@LobbyPrivate", StringComparison.OrdinalIgnoreCase)) SetLobbyTypePrivate();
            else if (name.Equals("@Mirror", StringComparison.OrdinalIgnoreCase)) PlaceMirror();
            else if (name.Equals("@MirrorToMe", StringComparison.OrdinalIgnoreCase)) TeleportMirrorToPlayer();
            else if (name.StartsWith("@JoinLobby=", StringComparison.OrdinalIgnoreCase)) JoinLobby(name.Substring("@JoinLobby=".Length).Trim());
            else if (name.Equals("@LobbyCode", StringComparison.OrdinalIgnoreCase)) LogLobbyCode();
            else if (name.Equals("@Peers", StringComparison.OrdinalIgnoreCase)) LogPeers();
            else _h.LogWarning($"[auto] unknown directive '{name}'");
            return;
        }

        // Wait for the element instead of trusting timers: the UI comes up at very
        // different speeds (Steam emulation is markedly slower than a normal launch).
        int hits = ActivateOrClick(name);
        if (hits == 0)
        {
            _clickWait += 0.5f;
            if (_clickWait > 30f)
            {
                _h.LogWarning($"[auto] gave up waiting for '{name}' after {_clickWait:F0}s");
                _abortSequence = true;
                DumpUi();
                return;
            }
            _nextClickAt = _t + 0.5f;
            return;
        }

        _clickWait = 0f;
        _clickIndex++;
        _nextClickAt = _t + _cfg.ClickStepDelay;
    }
    private float _clickWait;

