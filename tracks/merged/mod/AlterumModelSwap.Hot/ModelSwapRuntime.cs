    private void PlaceMirror()
    {
        var log = _h;
        try
        {
            DestroyMirror();
            string scene = SceneManager.GetActiveScene().name;
            if (_cfg.MirrorLobbyOnly && (scene == null || scene.IndexOf("Lobby", StringComparison.OrdinalIgnoreCase) < 0))
            {
                log.LogInfo($"[mirror] fixed Lobby mirror not placed in '{scene}'");
                return;
            }

            var cam = FindGameCamera();
            if (cam == null) { log.LogWarning("[mirror] no game camera"); return; }
            log.LogInfo($"[mirror] using camera '{PathOf(cam.transform)}' at {cam.transform.position}");
            var player = FindLocalPlayer();
            if (player == null) { log.LogWarning("[mirror] local player not found"); return; }

            _mirrorRt = MirrorFactory.Create(log, player, cam,
                _cfg.MirrorWidth,
                _cfg.MirrorHeight,
                _cfg.MirrorOffset,
                _cfg.MirrorCenterHeight,
                _cfg.MirrorFrame,
                _cfg.MirrorShowPlayer,
                _cfg.MirrorTilt,
                _cfg.MirrorBottomOnFloor,
                _cfg.MirrorSnapToWall,
                _cfg.MirrorEyeHeight,
                UseFixedLobbyPose, FixedLobbyPos,
                Quaternion.Euler(FixedLobbyEuler));

            if (_mirrorRt == null) { log.LogError("[mirror] creation failed"); return; }
            // Cosmetics render through the mirror's view scope and need its culling mask; wire the
            // two together before the first render so a hat is never missing for one frame.
            _mirrorRt.Cosmetics = _cosmetics;
            _cosmetics?.SetMirrorCamera(_mirrorRt.reflectCam);
            // The cosmetic bit follows the body bit (one answer, two masks): MirrorPlayerVisibility
            // owns it and calls back here the moment it changes, including in LateUpdate.
            _mirrorRt.Visibility?.SetBodyOnScreenSink(_cosmetics == null ? null : new Action<bool>(_cosmetics.OnLocalBodyOnScreenChanged));
            _mirror = _mirrorRt.Root;
        }
        catch (Exception e) { log.LogError($"[mirror] PlaceMirror failed: {e}"); }
    }

    public void LateUpdate()
    {
        // Ordering, all three tracks' constraints in one place:
        //  1. jiggle (bones) before the mirror renders, so the chest offset is on the skeleton for
        //     the frame the mirror camera draws;
        //  2. emote pose (emotes) before the mirror renders, so the mirror shows this frame's clip;
        //  3. cage counter-scale re-assert (bones) after the LAST skeleton writer, so an emote pose
        //     cannot leave spine_05/clavicle/neck at the cage scale;
        //  4. mirror render;
        //  5. emote bookkeeping (strip shots) after the render;
        //  6. jiggle probe after everything.
        // Two writers must never touch chest_02_l/r: while an emote owns the skeleton the solve is
        // suspended (see JiggleSolver.SetSuppressed), so 1 is a no-op and 2 is the only writer.
        bool emoteOwns = _emote != null && _emote.SkeletonOwned;
        Perf.Phase("late");
        JiggleSolver.SetSuppressed(_h, emoteOwns, emoteOwns ? "emote" : "animation");
        Perf.W("late.jigsolve", () => JiggleSolver.LateTick(_h));
        Perf.W("late.emote", () => _emote?.PostAnimationUpdate(_emoteDt));
        // Cage children (shoulders/neck/head) are position-pinned to 1/s; the animator and the
        // emote pose both rewrite local positions, so re-assert them now - after every writer,
        // before the mirror draws. No-op unless the cage scale is in effect.
        try { Perf.W("late.bounds", () => _proportions?.LateTick()); } catch (Exception e) { _h.LogWarning($"[bounds:late] {e.Message}"); }
        // Rigged Sahur retarget: after every skeleton writer, before the mirror draws, so the frame
        // the mirror renders is this frame's pose. Reads the game bones, writes only our own 71.
        try { Perf.W("late.sahurrig", () => SahurRig.LateTick(_h)); } catch (Exception e) { _h.LogWarning($"[sahurrig:late] {e.Message}"); }
        // The preview's retarget reads the preview skeleton, so it has its own late pass: same
        // ordering rule (after every writer), different bones.
        try { Perf.W("late.preview", () => SahurPreview.LateTick(_h)); } catch (Exception e) { _h.LogWarning($"[sahur:preview:late] {e.Message}"); }
        // Remote players' rigged retargets: same rule again, against each remote skeleton, before
        // the mirror draws this frame.
        try { Perf.W("late.remote", () => RemoteModels.LateTick(_h)); } catch (Exception e) { _h.LogWarning($"[swap:remote:late] {e.Message}"); }
        // Results rigged retargets, same ordering rule as the remote pass above.
        try { Perf.W("late.resultsbody", () => ResultsBodies.LateTick(_h)); } catch (Exception e) { _h.LogWarning($"[results:body:late] {e.Message}"); }
        if (_mirrorRt != null) { try { Perf.W("late.mirror", () => _mirrorRt.Tick()); } catch (Exception e) { _h.LogError($"[mirror] tick failed: {e}"); } }
        Perf.W("late.emotebook", () => _emote?.LateUpdate());
        // A clip that ends inside the pose write (non-looping) is published here, not with the
        // pre-write state read above.
        try { RemoteModels.PublishLocalEmote(null, _emote == null ? "" : _emote.PlayingId); } catch { }
        Perf.W("late.jigprobe", () => JiggleProbe.LateTick(_h));
        // Last thing in the frame: the third-person camera's fallback hook. The normal hook is
        // CinemachineCore.CameraUpdatedEvent (fired by the brain's own LateUpdate), so this is a
        // no-op unless that event is not delivering.
        Perf.W("late.mirrorvis", () => _mirrorRt?.Visibility?.LateTick());
    }

    // Single teardown path: removal, re-placement, config re-apply, scene change and reload.
    private void DestroyMirror()
    {
        var rt = _mirrorRt; _mirrorRt = null;
        if (rt != null) { try { rt.Dispose(); } catch (Exception e) { _h.LogWarning($"[mirror] dispose failed: {e.Message}"); } }
        var go = _mirror; _mirror = null;
        if (go != null) { try { UnityEngine.Object.Destroy(go); } catch { } }
    }

    // Retiring this generation must not leave a stale mirror, scaled skeletons, jiggle offsets,
    // an emote lease or cosmetic objects in the scene.
    public void Dispose()
    {
        // The lease and the freeze probe can both touch Animator.enabled. Keep the rig reference
        // across the whole teardown and log the surviving value at the end: that pair (lease state,
        // actual Animator.enabled) is the P2.2 evidence, not the order the passes happen to run in.
        var emote = _emote;
        Animator animator = null;
        bool leaseBefore = false;
        try { animator = emote?.AnimatorRef; leaseBefore = emote != null && emote.LeaseHeld; } catch { }

        // The picker owns no lease and only borrows the game camera for captures; close it first so
        // its cursor state and overlay texture do not outlive the generation.
        try { _pickers?.Dispose(); } catch (Exception e) { _h.LogWarning($"[picker] dispose failed: {e.Message}"); }
        _pickers = null;
        // Release the emote lease first: it restores the skeleton the other passes then work on.
        try { _emote?.Dispose(); } catch (Exception e) { _h.LogWarning($"[emote] dispose failed: {e.Message}"); }
        _emote = null;
        bool leaseAfter = false;
        try { leaseAfter = emote != null && emote.LeaseHeld; } catch { }
        try { JiggleProbe.Abort(_h); } catch { }
        string animatorAfter = "none";
        try { if (animator != null) animatorAfter = animator.enabled ? "true" : "false"; } catch { animatorAfter = "dead"; }
        try
        {
            _h.LogInfo($"[swap:teardown] leaseHeld={leaseBefore}->{leaseAfter} animatorEnabled={animatorAfter} " +
                       $"probeActive={JiggleProbe.IsActive} emoteLeases={PosePlayer.LeasesHeld}");
        }
        catch { }
        // Strip the jiggle offset before the bone pass restores its own recorded transforms.
        try { JiggleSolver.Shutdown(_h); } catch (Exception e) { _h.LogWarning($"[jsolve] shutdown failed: {e.Message}"); }
        try { ClothMetrics.Shutdown(_h); } catch (Exception e) { _h.LogWarning($"[bounds:cost] shutdown failed: {e.Message}"); }
        try { _proportions?.Dispose(); } catch (Exception e) { _h.LogWarning($"[bounds] dispose failed: {e.Message}"); }
        _proportions = null;
        try { ClothSim.OnDispose(_h); } catch { }
        // Stage-2 sync: release every remote lease (native renderers back) and destroy every remote
        // body while the rig/asset statics this generation built them from are still valid.
        try { RemoteModels.Dispose(_h); } catch (Exception e) { _h.LogWarning($"[swap:remote] dispose failed: {e.Message}"); }
        // Garments first, mirror second: the mirror's RestoreBinding rewrites its per-renderer
        // snapshot afterwards, and a new generation scrubs any garment flag that survives that.
        try { SahurModel.Dispose(_h); } catch (Exception e) { _h.LogWarning($"[sahur] dispose failed: {e.Message}"); }
        try { SahurRig.Dispose(_h); } catch (Exception e) { _h.LogWarning($"[sahurrig] dispose failed: {e.Message}"); }
        // Display state is per generation: the cached identities, drift flags and one-shot log keys
        // die with it, so the next generation re-projects from scratch instead of trusting a stale
        // "already correct" verdict.
        try { ModelPresentation.Reset(); } catch { }
        try { SahurWardrobe.Dispose(_h); } catch (Exception e) { _h.LogWarning($"[sahur:wardrobe] dispose failed: {e.Message}"); }
        try { SahurPreview.Dispose(_h); } catch (Exception e) { _h.LogWarning($"[sahur:preview] dispose failed: {e.Message}"); }
        try { ClothesToggle.Shutdown(_h); } catch (Exception e) { _h.LogWarning($"[clothes] dispose failed: {e.Message}"); }
        DestroyMirror();
        for (int i = 0; i < _reels.Count; i++)
        {
            try { _reels[i]?.Dispose(); }
            catch (Exception e) { _h.LogWarning($"[prop] dispose failed: {e.Message}"); }
        }
        _reels.Clear();
        _manual = null;
        // After the mirror is gone: its view scope must not survive the camera it scoped.
        try { _cosmetics?.Dispose(); } catch (Exception e) { _h.LogWarning($"[cosmetic:dispose-failed] {e.Message}"); }
        _cosmetics = null;
    }

