        // Reel drawn prompt / message: the fallback for when the cloned interactable's native
        // world prompt cannot display, plus the last-resort IMGUI plates. Never touches the game's
        // shared HUD prompt list, and never drawn alongside the native prompt.
        try { ReelHud.OnGUI(); } catch { }
        // The picker draws one texture; drawn before the mirror buttons so a button cannot sit on
        // top of it.
        _pickers?.OnGUI();
        if (!_cfg.MirrorOverlay) return;
        try
        {
            // Labels carry no hotkey: neither action has a key in the merged map (F7 is the POV
            // toggle, F9 cycles emote clips). The legend below is the only displayed shortcut list,
            // and every entry is the handler that actually polls it.
            if (GUI.Button(new Rect(18f, 18f, 250f, 32f), "Mirror to me")) TeleportMirrorToPlayer();
            if (GUI.Button(new Rect(18f, 56f, 250f, 32f), "Remove mirror")) RemoveMirror();
            GUI.Label(new Rect(18f, 92f, 600f, 38f), ModBindings.Legend());
            if (!string.IsNullOrEmpty(_overlayInfo))
                GUI.Label(new Rect(18f, 132f, 560f, 48f), _overlayInfo);
        }
        catch { }
    }

