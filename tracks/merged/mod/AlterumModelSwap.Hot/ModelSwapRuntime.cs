            try { gender = d.Gender.ToString(); } catch { }
            sb.AppendLine($"  [{i}] '{d.name}' index={idx} gender={gender} third='{third}' first='{first}'");
        }
        log.LogInfo("=== PlayerModelData ===\n" + sb);
        return true;
    }
