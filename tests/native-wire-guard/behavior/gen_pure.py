#!/usr/bin/env python3
"""Extract SahurWardrobe's marked pure-decision block verbatim for the behavioral harness.

The native-wire decisions live in `SahurWardrobe.cs` (a file that cannot be compiled outside the
game because of its Il2Cpp/Harmony surface). The block between the two markers below contains only
`System` types, so the harness can compile the SHIPPING text itself - not a copy and not a second
implementation - by lifting it into a generated source file with the namespace the production file
declares. Comments/strings in the block are irrelevant: if the block ever references a game type,
the harness compile fails, which is exactly the purity the markers promise.

Run:  python3 tests/native-wire-guard/behavior/gen_pure.py <output.cs>
Exit: 0 extracted, 1 the markers are missing/duplicated or the source cannot be read.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
SOURCE = ROOT / "tracks/merged/mod/AlterumModelSwap.Hot/SahurWardrobe.cs"
BEGIN = "// >>> native-wire-pure: begin"
END = "// <<< native-wire-pure: end"

HEADER = """// <auto-generated>
// Extracted verbatim from tracks/merged/mod/AlterumModelSwap.Hot/SahurWardrobe.cs by
// tests/native-wire-guard/behavior/gen_pure.py. Do not edit; edit the source block.
// </auto-generated>
using System;
using System.Collections.Generic;

namespace AlterumModelSwap.Hot
{
"""

FOOTER = "}\n"


def extract(source: pathlib.Path) -> str:
    text = source.read_text(encoding="utf-8")
    begins = text.count(BEGIN)
    ends = text.count(END)
    if begins != 1 or ends != 1:
        raise SystemExit(f"{source}: want exactly one begin/end marker, found {begins}/{ends}")
    start = text.index(BEGIN)
    end = text.index(END)
    if end <= start:
        raise SystemExit(f"{source}: the end marker precedes the begin marker")
    body = text[start:end]
    # Keep the marker line out of the compiled text but keep the blank line after it readable.
    newline = body.find("\n")
    if newline < 0:
        raise SystemExit(f"{source}: the begin marker has no body")
    block = body[newline + 1:]
    if "namespace " in block:
        raise SystemExit(f"{source}: the pure block must not declare a namespace")
    return block


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", help="path of the generated .cs file")
    args = parser.parse_args()

    block = extract(SOURCE)
    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    tmp = output.with_suffix(output.suffix + ".tmp")
    tmp.write_text(HEADER + block + FOOTER, encoding="utf-8")
    tmp.replace(output)
    print(f"native-wire pure block: {len(block.splitlines())} lines -> {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
